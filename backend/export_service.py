#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Export service for TimeTrack Visual Analytics.
Exports selected date ranges or single days to CSV, JSON, and Markdown formats.
"""

import csv
import datetime
import json
import io
from pathlib import Path
from typing import Dict, Any, List, Optional


class TimeTrackExportService:
    def __init__(self, query_service):
        self.query_service = query_service

    def export_csv(self, start_date: str, end_date: str, target_file: Optional[Path] = None) -> str:
        """Exports all records in date range to CSV string or file."""
        records = self.query_service.reader.query("""
            SELECT id, start_time, end_time, duration_seconds, app_name, app_id, window_title, category, is_locked, is_idle
            FROM window_activities
            WHERE date(start_time) >= date(?) AND date(start_time) <= date(?)
            ORDER BY start_time ASC;
        """, (start_date, end_date))

        output = io.StringIO()
        fieldnames = ["id", "start_time", "end_time", "duration_seconds", "app_name", "app_id", "window_title", "category", "is_locked", "is_idle"]
        writer = csv.DictWriter(output, fieldnames=fieldnames)
        writer.writeheader()
        for r in records:
            writer.writerow(dict(r))

        content = output.getvalue()
        if target_file:
            path = Path(target_file)
            path.parent.mkdir(parents=True, exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)
        return content

    def export_json(self, start_date: str, end_date: str, target_file: Optional[Path] = None) -> str:
        """Exports overview and full records for date range to JSON."""
        overview = self.query_service.get_overview(start_date, end_date)
        records = self.query_service.reader.query("""
            SELECT id, start_time, end_time, duration_seconds, app_name, app_id, window_title, category, is_locked, is_idle
            FROM window_activities
            WHERE date(start_time) >= date(?) AND date(start_time) <= date(?)
            ORDER BY start_time ASC;
        """, (start_date, end_date))

        payload = {
            "metadata": {
                "start_date": start_date,
                "end_date": end_date,
                "exported_at": datetime.datetime.now().isoformat(),
                "record_count": len(records)
            },
            "overview": overview,
            "records": [dict(r) for r in records]
        }
        content = json.dumps(payload, ensure_ascii=False, indent=2)
        if target_file:
            path = Path(target_file)
            path.parent.mkdir(parents=True, exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)
        return content

    def export_markdown(self, start_date: str, end_date: str, target_file: Optional[Path] = None) -> str:
        """Exports formatted summary report in Markdown."""
        ov = self.query_service.get_overview(start_date, end_date)
        md = []
        md.append(f"# 📊 TimeTrack Analytics Report ({start_date} to {end_date})\n")
        md.append(f"> Generated by TimeTrack Visual Analytics Dashboard\n")
        md.append("## 1. Executive Summary")
        md.append(f"- **Active Focus Time**: `{ov['active_formatted']}` ({ov['active_percent']}%)")
        md.append(f"- **Locked / Away Time**: `{ov['locked_formatted']}` ({ov['locked_percent']}%)")
        md.append(f"- **Total Tracked Time**: `{ov['online_formatted']}`")
        md.append(f"- **Distinct Applications**: `{ov['app_count']}`")
        md.append(f"- **Daily Average Active**: `{ov['daily_avg_active_formatted']}`")
        md.append(f"- **Most Used Application**: **{ov['top_app']['name']}** ({ov['top_app']['formatted']})")
        md.append(f"- **Most Used Category**: {ov['top_category']['icon']} **{ov['top_category']['name']}** ({ov['top_category']['formatted']})\n")

        md.append("## 2. Category Distribution")
        md.append("| Category | Duration | Share |")
        md.append("| :--- | :--- | :--- |")
        for c in ov["category_distribution"]:
            md.append(f"| {c['icon']} **{c['name']}** | `{c['formatted']}` | {c['percent']}% |")

        md.append("\n## 3. Top Applications")
        md.append("| Rank | Application | Duration | Active Share |")
        md.append("| :---: | :--- | :--- | :--- |")
        for idx, a in enumerate(ov["top_apps"], 1):
            md.append(f"| {idx} | **{a['name']}** | `{a['formatted']}` | {a['percent']}% |")

        content = "\n".join(md)
        if target_file:
            path = Path(target_file)
            path.parent.mkdir(parents=True, exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)
        return content
